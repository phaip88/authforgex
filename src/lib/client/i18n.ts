const dicts: Record<Lang, Record<Key, string>> = { en, zh };

// ---------- prefs store ----------
function readLS(k: string): string | null {
  try {
    return typeof window === "undefined" ? null : localStorage.getItem(k);
  } catch {
    return null;
  }
}

function detectLang(): Lang {
  const saved = readLS("af-lang");
  if (saved === "en" || saved === "zh") return saved;
  const nav = typeof navigator !== "undefined" ? navigator.language?.toLowerCase() ?? "" : "";
  return nav.startsWith("zh") ? "zh" : "en";
}

function detectTheme(): Theme {
  const saved = readLS("af-theme");
  if (saved === "light" || saved === "dark") return saved;
  return typeof window !== "undefined" && window.matchMedia?.("(prefers-color-scheme: light)").matches ? "light" : "dark";
}

function applyTheme(theme: Theme) {
  document.documentElement.dataset.theme = theme;
  document.documentElement.style.colorScheme = theme;
}
function applyLang(lang: Lang) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
}

interface Prefs {
  lang: Lang;
  theme: Theme;
  setLang: (l: Lang) => void;
  setTheme: (t: Theme) => void;
  toggleTheme: () => void;
}

export const usePrefs = create<Prefs>((set, get) => ({
  lang: detectLang(),
  theme: detectTheme(),
  setLang: (lang) => {
    try {
      localStorage.setItem("af-lang", lang);
    } catch { /* private mode */ }
    applyLang(lang);
    set({ lang });
  },
  setTheme: (theme) => {
    try {
      localStorage.setItem("af-theme", theme);
    } catch { /* private mode */ }
    applyTheme(theme);
    set({ theme });
  },
  toggleTheme: () => get().setTheme(get().theme === "dark" ? "light" : "dark"),
}));

export type TFunc = (k: Key, vars?: Record<string, string | number>) => string;

function makeT(lang: Lang): TFunc {
  return (k, vars) => {
    let s: string = dicts[lang][k] ?? en[k] ?? k;
    if (vars) for (const [key, v] of Object.entries(vars)) s = s.replaceAll(`{${key}}`, String(v));
    return s;
  };
}

/** Non-hook translator (store / callbacks). */
export const getT = (): TFunc => makeT(usePrefs.getState().lang);

/** Hook translator — re-renders on language change. */
export function useT(): TFunc {
  const lang = usePrefs((s) => s.lang);
  return makeT(lang);
}

export function useLocale(): string {
  return usePrefs((s) => (s.lang === "zh" ? "zh-CN" : "en-US"));
}

export function fmtAgoT(ts: number, t: TFunc): string {
  const s = Math.max(0, Math.floor((Date.now() - ts) / 1000));
  if (s < 60) return t("time.sAgo", { n: s });
  const m = Math.floor(s / 60);
  if (m < 60) return t("time.mAgo", { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return t("time.hAgo", { n: h });
  return t("time.dAgo", { n: Math.floor(h / 24) });
}

